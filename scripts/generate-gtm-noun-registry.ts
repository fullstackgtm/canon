import { existsSync, readdirSync, readFileSync, watch, writeFileSync } from "node:fs";
import { basename, join, relative, resolve } from "node:path";

const nounDir = resolve(process.cwd(), "convex/lib/gtmNouns");
const generatedPath = join(nounDir, "index.generated.ts");
const watchMode = process.argv.includes("--watch");

type NounExport = {
  file: string;
  importPath: string;
  exportName: string;
  noun: string;
};

function main() {
  generate();
  if (!watchMode) return;

  console.log(`[gtm:nouns] watching ${relative(process.cwd(), nounDir)}`);
  let timeout: NodeJS.Timeout | null = null;
  watch(nounDir, { persistent: true }, (_event, fileName) => {
    if (!fileName || !fileName.endsWith(".ts")) return;
    if (fileName === "index.generated.ts") return;
    if (timeout) clearTimeout(timeout);
    timeout = setTimeout(() => {
      try {
        generate();
      } catch (error) {
        console.error("[gtm:nouns] generation failed", error);
      }
    }, 50);
  });
}

function generate() {
  if (!existsSync(nounDir)) {
    throw new Error(`Noun directory does not exist: ${nounDir}`);
  }

  const exports = discoverNounExports();
  const content = renderGeneratedRegistry(exports);
  const previous = existsSync(generatedPath)
    ? readFileSync(generatedPath, "utf8")
    : null;

  if (previous !== content) {
    writeFileSync(generatedPath, content);
    console.log(
      `[gtm:nouns] generated ${relative(process.cwd(), generatedPath)} (${exports.length} nouns)`,
    );
  } else if (!watchMode) {
    console.log(
      `[gtm:nouns] ${relative(process.cwd(), generatedPath)} is up to date (${exports.length} nouns)`,
    );
  }
}

function discoverNounExports(): NounExport[] {
  const files = readdirSync(nounDir)
    .filter((file) => file.endsWith(".ts"))
    .filter((file) => file !== "index.ts" && file !== "index.generated.ts")
    .sort();

  const nouns: NounExport[] = [];
  for (const file of files) {
    const absolute = join(nounDir, file);
    const source = readFileSync(absolute, "utf8");
    const exportRegex = /export\s+const\s+(\w+PrimitiveSpec)\s*=([\s\S]*?)(?=\nexport\s+const\s+\w+PrimitiveSpec\s*=|\n(?:export\s+)?type\s+|\nfunction\s+|\nconst\s+\w+\s*=|$)/g;
    let match: RegExpExecArray | null;
    while ((match = exportRegex.exec(source))) {
      const exportName = match[1];
      const block = match[2];
      const nounMatch = block.match(/\bnoun:\s*["']([a-z0-9_]+)["']/);
      if (!nounMatch) {
        throw new Error(
          `${relative(process.cwd(), absolute)} exports ${exportName} but does not declare noun: "..."`,
        );
      }
      nouns.push({
        file,
        importPath: `./${basename(file, ".ts")}`,
        exportName,
        noun: nounMatch[1],
      });
    }
  }

  const duplicate = firstDuplicate(nouns.map((entry) => entry.noun));
  if (duplicate) throw new Error(`Duplicate GTM noun id: ${duplicate}`);
  return nouns.sort((a, b) => a.noun.localeCompare(b.noun));
}

function renderGeneratedRegistry(exports: NounExport[]) {
  const byFile = new Map<string, NounExport[]>();
  for (const entry of exports) {
    byFile.set(entry.file, [...(byFile.get(entry.file) ?? []), entry]);
  }

  const imports = [...byFile.entries()]
    .sort(([a], [b]) => a.localeCompare(b))
    .map(([file, entries]) => {
      const names = entries
        .map((entry) => entry.exportName)
        .sort()
        .join(",\n  ");
      return `import {\n  ${names},\n} from "./${basename(file, ".ts")}";`;
    })
    .join("\n");

  const registry = exports
    .map((entry) => `  ${JSON.stringify(entry.noun)}: ${entry.exportName},`)
    .join("\n");

  const exportNames = exports
    .map((entry) => entry.exportName)
    .sort()
    .map((name) => `  ${name},`)
    .join("\n");

  return `// This file is generated by scripts/generate-gtm-noun-registry.ts.\n// Do not edit by hand. Add or update noun specs in this folder, then run npm run gtm:nouns.\n\n${imports}\n\nexport const gtmNounSpecs = {\n${registry}\n} as const;\n\nexport type GtmNounId = keyof typeof gtmNounSpecs;\nexport type GtmNounSpec = (typeof gtmNounSpecs)[GtmNounId];\n\nexport {\n${exportNames}\n};\n`;
}

function firstDuplicate(values: string[]) {
  const seen = new Set<string>();
  for (const value of values) {
    if (seen.has(value)) return value;
    seen.add(value);
  }
  return null;
}

main();
